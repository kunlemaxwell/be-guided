#!/usr/bin/env node
// Builds the whole admin as one page for the chat (MCP Apps, ui://be-guided/admin.html):
// the same screens as the web admin, compiled with VITE_WIDGET=1 so every server call
// goes through the connector's admin_api tool (admin/web/src/widget/host.ts).
// Writes backend/src/ui/admin-html.generated.ts. Run after changing the admin or the Studio:
//   node scripts/build-studio.mjs && node scripts/build-admin-app.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'admin/web/dist-chat');

await build({
  configFile: path.join(root, 'admin/web/vite.config.ts'),
  mode: 'production',
  logLevel: 'warn',
  define: { 'import.meta.env.VITE_WIDGET': JSON.stringify('1') },
  build: {
    outDir,
    emptyOutDir: true,
    assetsInlineLimit: 100_000_000,
    cssCodeSplit: false,
    modulePreload: false,
    rollupOptions: { output: { inlineDynamicImports: true } },
  },
});

let html = fs.readFileSync(path.join(outDir, 'index.html'), 'utf8');

const read = (href) => fs.readFileSync(path.join(outDir, href.replace(/^\//, '')), 'utf8');

// The admin follows the computer's light/dark setting; in the chat, the chat's theme decides.
const adminCss = fs.readFileSync(path.join(root, 'admin/web/src/styles.css'), 'utf8');
const light = adminCss.match(/^:root \{([\s\S]*?)^\}/m)?.[1];
const dark = adminCss.match(/@media \(prefers-color-scheme: dark\) \{\s*:root \{([\s\S]*?)\n  \}/)?.[1];
if (!light || !dark) throw new Error('Could not find the admin colour tokens.');
const themed = `:root[data-theme='light'] {${light}}\n:root[data-theme='dark'] {${dark}}\n`;

html = html.replace(/<link rel="stylesheet"[^>]*href="([^"]+)"[^>]*>/g, (_, href) => `<style>${read(href)}\n${themed}</style>`);
// Module scripts run after parsing, so the inlined one moves to the end of <body> where #root exists.
let script = '';
html = html.replace(/<script type="module"[^>]*src="([^"]+)"[^>]*><\/script>/g, (_, href) => {
  script += read(href).replace(/<\/script/gi, '<\\/script');
  return '';
});
if (!script) throw new Error('No script found in the built admin.');
html = html.replace('</body>', () => `<script type="module">${script}</script>\n</body>`);
if (/(src|href)="\/assets\//.test(html)) throw new Error('Some admin files were not inlined.');

const ts = `// Generated by scripts/build-admin-app.mjs from admin/web. Do not edit.\nexport const ADMIN_HTML = ${JSON.stringify(html)};\n`;
fs.writeFileSync(path.join(root, 'backend/src/ui/admin-html.generated.ts'), ts);
fs.rmSync(outDir, { recursive: true, force: true });
console.log(`wrote backend/src/ui/admin-html.generated.ts (${Math.round(html.length / 1024)} KB)`);

