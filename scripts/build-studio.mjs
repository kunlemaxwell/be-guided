#!/usr/bin/env node
// Builds the Studio app (studio/index.html) into the three places that serve it:
//  - backend/src/ui/studio-html.generated.ts  (the connector's in-chat app, ui://be-guided/studio.html)
//  - admin/web/public/studio.html             (the admin's Automatic checks and Reader feedback screens)
//  - packages/be-guided-studio/ui/studio.html (the local Studio package for Claude Code and Codex)
// Run after editing studio/index.html: node scripts/build-studio.mjs  (a test checks they are in step).
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = fs.readFileSync(path.join(root, 'studio/index.html'), 'utf8');

// The Studio wears the admin's own stylesheet, so the two look the same and admin style changes flow through.
// The admin follows the computer's light/dark setting; the Studio can also be told (?theme=, or by the chat host),
// so the admin's dark tokens are repeated for :root[data-theme='dark'] and its light tokens for [data-theme='light'].
const adminCss = fs.readFileSync(path.join(root, 'admin/web/src/styles.css'), 'utf8');
const light = adminCss.match(/^:root \{([\s\S]*?)^\}/m)?.[1];
const dark = adminCss.match(/@media \(prefers-color-scheme: dark\) \{\s*:root \{([\s\S]*?)\n  \}/)?.[1];
if (!light || !dark || !source.includes('/*ADMIN_STYLES*/')) throw new Error('Could not find the admin tokens or the /*ADMIN_STYLES*/ placeholder.');
const themed = `${adminCss}\n:root[data-theme='light'] {${light}}\n:root[data-theme='dark'] {${dark}}\n`;
const html = source.replace('/*ADMIN_STYLES*/', () => themed);
const ts = `// Generated by scripts/build-studio.mjs from studio/index.html. Do not edit.\nexport const STUDIO_HTML = ${JSON.stringify(html)};\n`;
const targets = [
  ['backend/src/ui/studio-html.generated.ts', ts],
  ['admin/web/public/studio.html', html],
  ['packages/be-guided-studio/ui/studio.html', html],
];
for (const [rel, text] of targets) {
  const file = path.join(root, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  console.log(`wrote ${rel} (${Math.round(text.length / 1024)} KB)`);
}

// The admin on Cloudflare sends strict headers on every page (no framing, no inline scripts).
// The Studio is shown in a frame inside the admin and is one file with an inline script, so
// /studio.html gets its own rule: same-origin framing only, and only this exact script (by hash).
const scripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m) => `'sha256-${crypto.createHash('sha256').update(m[1]).digest('base64')}'`);
const studioCsp = `default-src 'none'; script-src ${scripts.join(' ')}; style-src 'unsafe-inline'; connect-src 'self'; img-src 'self' data:; frame-ancestors 'self'; base-uri 'none'; form-action 'self'`;
const headersFile = path.join(root, 'admin/web/public/_headers');
// Both paths: Cloudflare may serve /studio.html as /studio.
const rule = (p) => `${p}\n  ! Content-Security-Policy\n  ! X-Frame-Options\n  Content-Security-Policy: ${studioCsp}\n  X-Frame-Options: SAMEORIGIN\n`;
const block = `# BEGIN studio (written by scripts/build-studio.mjs)\n${rule('/studio.html')}${rule('/studio')}# END studio\n`;
const current = fs.readFileSync(headersFile, 'utf8').replace(/# BEGIN studio[\s\S]*?# END studio\n/, '');
fs.writeFileSync(headersFile, `${current.trimEnd()}\n\n${block}`);
console.log('wrote admin/web/public/_headers (studio rule)');

// The shareable zip (served by the site at /editor-kit/be-guided-studio.zip).
const pkg = path.join(root, 'packages/be-guided-studio');
const zip = path.join(root, 'public/editor-kit/be-guided-studio.zip');
fs.rmSync(zip, { force: true });
execFileSync('zip', ['-r', '-X', '-q', zip, 'be-guided-studio', '-x', '*/node_modules/*', '*/.DS_Store'], { cwd: path.dirname(pkg) });
console.log(`wrote public/editor-kit/be-guided-studio.zip (${Math.round(fs.statSync(zip).size / 1024)} KB)`);
